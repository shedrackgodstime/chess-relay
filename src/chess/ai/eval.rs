/// Evaluates a board position from White's perspective (positive = good for White).
pub(crate) fn evaluate(board: &Board) -> i32 {
    let mut score = 0i32;
    for (file, rank, piece) in board.iter() {
        let value = piece_value(piece.piece_type) + piece_square_bonus(piece, file, rank);
        match piece.color {
            PieceColor::White => score += value,
            PieceColor::Black => score -= value,
        }
    }
    score
}

pub(crate) fn piece_value(piece_type: PieceType) -> i32 {
    match piece_type {
        PieceType::Pawn => PAWN_VALUE,
        PieceType::Knight => KNIGHT_VALUE,
        PieceType::Bishop => BISHOP_VALUE,
        PieceType::Rook => ROOK_VALUE,
        PieceType::Queen => QUEEN_VALUE,
        PieceType::King => KING_VALUE,
    }
}

fn piece_square_bonus(piece: Piece, file: u8, rank: u8) -> i32 {
    let rank = if piece.color == PieceColor::Black {
        7 - rank
    } else {
        rank
    } as usize;
    let file = file as usize;
    match piece.piece_type {
        PieceType::Pawn => PAWN_TABLE[rank][file],
        PieceType::Knight => KNIGHT_TABLE[rank][file],
        PieceType::Bishop => BISHOP_TABLE[rank][file],
        PieceType::Rook => ROOK_TABLE[rank][file],
        PieceType::Queen => QUEEN_TABLE[rank][file],
        PieceType::King => KING_TABLE[rank][file],
    }
}
